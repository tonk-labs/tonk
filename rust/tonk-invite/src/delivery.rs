//! Account-bound completion of an invitation held by an email delivery service.
//! The original signed grant supplies provenance; the completion supplies authority.

use anyhow::{Context, Result, ensure};
use dialog_credentials::DidKeyResolver;
use dialog_ucan_core::DelegationChain;
use dialog_varsig::Did;
use ipld_core::ipld::Ipld;
use serde::{Deserialize, Serialize};

use crate::{Invite, InviteAudience};

/// Signed metadata identifying a pending delivery without publishing its email.
pub const DELIVERY_ID: &str = "invitation.delivery";

/// An opaque, unguessable delivery identifier generated by the sending client.
pub fn valid_id(id: &str) -> bool {
    id.len() == 64
        && id
            .bytes()
            .all(|byte| byte.is_ascii_hexdigit() && !byte.is_ascii_uppercase())
}

/// The two artifacts returned only to the verified recipient. No delivery seed.
#[derive(Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct DeliveryEnvelope {
    /// Immutable pending-record identifier, signed into the original grant.
    pub invitation: String,
    /// Base58-encoded original delegation chain signed by the inviter.
    pub original: String,
    /// Base58-encoded chain with exactly one recipient-bound completion hop.
    pub completed: String,
}

impl DeliveryEnvelope {
    /// Validate the original grant, completion continuity, signatures and recipient.
    /// UCAN scope/expiry/revocation admission still occurs at the ordinary join boundary.
    pub async fn into_invite(&self, recipient: &Did, expected_id: &str) -> Result<Invite> {
        ensure!(
            valid_id(expected_id) && self.invitation == expected_id,
            "wrong delivery identifier"
        );
        let original =
            DelegationChain::try_from(bs58::decode(&self.original).into_vec()?.as_slice())?;
        let completed =
            DelegationChain::try_from(bs58::decode(&self.completed).into_vec()?.as_slice())?;
        ensure!(
            completed.audience() == recipient,
            "wrong delivery recipient"
        );
        ensure!(
            original.subject().is_some() && original.subject() == completed.subject(),
            "changed delivery subject"
        );
        let prefix: Vec<_> = original.proofs().collect();
        let proofs: Vec<_> = completed.proofs().collect();
        let original_leaf = prefix.last().context("missing original grant")?;
        ensure!(
            original_leaf.meta().get(DELIVERY_ID) == Some(&Ipld::String(expected_id.into())),
            "delivery not bound to original grant"
        );
        ensure!(
            proofs.len() == prefix.len() + 1,
            "delivery must append exactly one grant"
        );
        for (a, b) in prefix.iter().zip(&proofs) {
            ensure!(a.to_cid() == b.to_cid(), "original grant substituted");
        }
        for proof in &proofs {
            proof.verify_signature(&DidKeyResolver).await?;
        }
        ensure!(
            proofs.last().context("missing completion")?.issuer() == original.audience(),
            "wrong delivery signer"
        );
        crate::inviter(&original)?.context("original invitation has no signed inviter")?;
        let mut invite = Invite::new(
            completed,
            InviteAudience::Scoped,
            crate::home_address(&original)?,
        )
        .await?;
        invite.space_name = crate::space_name(&original);
        invite.original = Some(original);
        Ok(invite)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use dialog_credentials::{Ed25519Signer, Signer};
    use dialog_ucan_core::{DelegationBuilder, subject::Subject};
    use dialog_varsig::Principal;
    use std::collections::BTreeMap;

    async fn envelope(id: &str) -> (DeliveryEnvelope, Did, Did) {
        let space = Ed25519Signer::generate().await.unwrap();
        let alice = Ed25519Signer::generate().await.unwrap();
        let bob = Ed25519Signer::generate().await.unwrap();
        let delivery = Ed25519Signer::import(&[42; 32]).await.unwrap();
        let carol = Ed25519Signer::generate().await.unwrap();
        let mut meta = crate::inviter_meta(&bob.did());
        meta.insert(DELIVERY_ID.into(), Ipld::String(id.into()));
        let mut chain: Option<DelegationChain> = None;
        for (issuer, audience, metadata) in [
            (&space, alice.did(), BTreeMap::new()),
            (&alice, bob.did(), BTreeMap::new()),
            (&bob, delivery.did(), meta),
        ] {
            let grant = DelegationBuilder::new()
                .issuer(Signer::from(issuer.clone()))
                .audience(&audience)
                .subject(Subject::Specific(space.did()))
                .command(vec!["use".into()])
                .meta(metadata)
                .try_build()
                .await
                .unwrap();
            chain = Some(match chain {
                None => DelegationChain::new(grant),
                Some(chain) => chain.push(grant).unwrap(),
            });
        }
        let original = chain.unwrap();
        let invite = Invite::new(
            original.clone(),
            InviteAudience::Open { seed: [42; 32] },
            None,
        )
        .await
        .unwrap();
        let completed = invite.claim(&carol.did()).await.unwrap().chain;
        (
            DeliveryEnvelope {
                invitation: id.into(),
                original: bs58::encode(original.to_bytes().unwrap()).into_string(),
                completed: bs58::encode(completed.to_bytes().unwrap()).into_string(),
            },
            carol.did(),
            bob.did(),
        )
    }

    #[dialog_common::test]
    async fn preserves_bob_through_completion_and_url_round_trip() {
        let id = "a".repeat(64);
        let (delivery, carol, bob) = envelope(&id).await;
        let invite = delivery.into_invite(&carol, &id).await.unwrap();
        assert_eq!(
            crate::inviter(invite.invitation_chain()).unwrap(),
            Some(bob.clone())
        );
        assert_eq!(crate::inviter(&invite.chain).unwrap(), None);
        let url = invite.to_url("https://tonk.example/join").unwrap();
        let parsed = Invite::parse_url(&url).await.unwrap();
        assert_eq!(
            crate::inviter(parsed.invitation_chain()).unwrap(),
            Some(bob)
        );
        assert!(parsed.claim(&carol).await.is_ok());
    }

    #[dialog_common::test]
    async fn rejects_wrong_recipient_identifier_and_substituted_original() {
        let id = "a".repeat(64);
        let (mut delivery, carol, _) = envelope(&id).await;
        let mallory = Ed25519Signer::generate().await.unwrap().did();
        assert!(delivery.into_invite(&mallory, &id).await.is_err());
        assert!(delivery.into_invite(&carol, &"b".repeat(64)).await.is_err());
        let (other, _, _) = envelope(&id).await;
        delivery.original = other.original;
        assert!(delivery.into_invite(&carol, &id).await.is_err());
    }
}
