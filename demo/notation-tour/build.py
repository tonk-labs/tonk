#!/usr/bin/env python3
"""Build the notation tour's seed: the notebook library plus the tour.

The tour is written as one Markdown document (tour.md): prose, and
```notation fences the notebook runs as cells. `space/create` seeds a new
space from ONE document, and a seed may not include another library
document, so the seed is generated: notebook.yaml as it is, then the tour
notebook as facts (its title, one block per Markdown block, and the
block sequence), then the space's home.

    python3 demo/notation-tour/build.py

writes rust/tonk-core/assets/library/notation-tour.yaml, which the app
serves at /library/notation-tour.yaml. Re-run it after editing tour.md or
notebook.yaml.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
LIBRARY = ROOT / "rust/tonk-core/assets/library"
TOUR = pathlib.Path(__file__).resolve().parent / "tour.md"
OUT = LIBRARY / "notation-tour.yaml"
NOTEBOOK = "notebook:notation-tour"


def chunks(text):
    """Blank-line separated chunks, a fence kept whole."""
    out, current, fenced = [], [], False
    for line in text.splitlines():
        if line.startswith("```"):
            fenced = not fenced
        if not fenced and line.strip() == "" and not line.startswith("```"):
            if current:
                out.append("\n".join(current))
                current = []
            continue
        current.append(line)
    if current:
        out.append("\n".join(current))
    return out


def blocks(text):
    """The notebook's blocks: a heading rides with what follows it."""
    out, pending = [], []
    for chunk in chunks(text):
        if chunk.startswith("#"):
            if any(not c.startswith("#") for c in pending):
                out.append("\n\n".join(pending))
                pending = []
            pending.append(chunk)
        elif any(c.startswith("#") for c in pending):
            pending.append(chunk)
            out.append("\n\n".join(pending))
            pending = []
        else:
            out.append(chunk)
    if pending:
        out.append("\n\n".join(pending))
    return out


def quote(text):
    return json.dumps(text, ensure_ascii=False)


def main():
    tour = TOUR.read_text()
    title = re.search(r"^# (.+)$", tour, re.M).group(1).strip()
    parts = blocks(tour)
    entries = ", ".join(
        f"N{at:05}V: id:notation-tour/block-{at}" for at in range(1, len(parts) + 1)
    )
    doc = [
        "# GENERATED by demo/notation-tour/build.py from notebook.yaml and",
        "# demo/notation-tour/tour.md. Do not edit; edit those and re-run it.",
        "#",
        "# The notation tour's seed: the notebook library, then the tour",
        "# notebook as facts, then the space's home, which opens it.",
        "",
        (LIBRARY / "notebook.yaml").read_text().rstrip(),
        "",
        "# ---------------------------------------------------------------------------",
        "# The tour notebook",
        "# ---------------------------------------------------------------------------",
        "",
        "notebook/named!:",
        f"  this: {NOTEBOOK}",
        f"  title: {quote(title)}",
        "",
        "notebook/blocks!:",
        f"  this: {NOTEBOOK}",
        f"  block: {{{entries}}}",
        "",
    ]
    for at, source in enumerate(parts, 1):
        doc += [
            "notebook/block!:",
            f"  this: id:notation-tour/block-{at}",
            f"  notebook: {NOTEBOOK}",
            f"  source: {quote(source)}",
            "",
        ]
    doc += [
        "# The space's home: the tour notebook.",
        "concept!: &notation-tour/home",
        "  this: space:home",
        "  description: The notation tour's home page.",
        "  with:",
        "    subject:",
        "      description: The repository's subject DID.",
        "      the: dialog.replica/subject",
        "      as: entity",
        "",
        "view!:",
        "  this: space:home",
        "  show:",
        "    ui: |",
        f"      <tonk-display entity={NOTEBOOK} model=notebook></tonk-display>",
        "",
        "name!:",
        "  this: id:tonk/space",
        "  entity: space:home",
        "",
    ]
    OUT.write_text("\n".join(doc))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(parts)} blocks")


if __name__ == "__main__":
    main()
