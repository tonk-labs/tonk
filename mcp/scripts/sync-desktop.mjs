import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { toolDefinitions } from '../catalog.mjs';
import { build } from 'esbuild';
import { guides, instructions } from '../authoring.mjs';
import { primitiveTools } from '../primitive.mjs';

const args = process.argv.slice(2);
const check = args.includes('--check');
const desktop =
  args.find((arg) => arg !== '--check') ??
  fileURLToPath(new URL('../../desktop/', import.meta.url));
if (args.filter((arg) => arg !== '--check').length > 1) {
  console.error('Usage: node scripts/sync-desktop.mjs [--check] [/path/to/desktop]');
  process.exit(1);
}
const source = await readFile(new URL('../tools.json', import.meta.url));
const hash = createHash('sha256').update(source).digest('hex');
const json = JSON.stringify(
  Object.fromEntries(toolDefinitions.map((tool) => [tool.name, tool])),
  null,
  2,
);
const output = `// Generated by tonk/mcp/scripts/sync-desktop.mjs. Do not edit.
// tools.json SHA-256: ${hash}
import Foundation

public enum TonkToolCatalog {
  public static let primitiveNames = ${JSON.stringify(primitiveTools)}
  public static let primitiveDefinitions = primitiveNames.map(definition)
  public static func definition(_ name: String) -> JSONValue {
    guard let tool = definitions[name] else {
      preconditionFailure("Unknown canonical Tonk tool: \\(name)")
    }
    return tool
  }

  private static let definitions: [String: JSONValue] = {
    // This literal is generated from validated JSON and checked before release.
    let data = Data(#"""
${json}
"""#.utf8)
    return try! JSONDecoder().decode([String: JSONValue].self, from: data)
  }()
}
`;
const bundled = await build({
  absWorkingDir: fileURLToPath(new URL('../', import.meta.url)),
  entryPoints: [fileURLToPath(new URL('../browser.mjs', import.meta.url))],
  bundle: true,
  write: false,
  format: 'iife',
  globalName: 'TonkAgent',
  platform: 'browser',
  target: 'es2022',
});
const context = `// Generated by tonk/mcp/scripts/sync-desktop.mjs. Do not edit.
import Foundation

public enum TonkAgentContext {
  public static let instructions = ${swiftString(instructions)}
  private static let guides: [String: String] = try! JSONDecoder().decode(
    [String: String].self, from: Data(${swiftString(JSON.stringify(guides))}.utf8))

  public static func guide(_ arguments: JSONValue) throws -> JSONValue {
    guard case .object(let fields) = arguments, Set(fields.keys).isSubset(of: ["topic"]) else {
      throw HarnessError.message("Provide only an optional guide topic.")
    }
    if fields.isEmpty {
      return .object(["topics": .array(topics.map(JSONValue.string)), "usage": .string(instructions)])
    }
    guard let topic = fields["topic"]?.string, let text = guides[topic] else {
      throw HarnessError.message("Unknown guide; omit topic to list available manuals.")
    }
    return .object(["topic": .string(topic), "source": .string("Canonical Tonk manual"), "text": .string(text)])
  }

  public static let topics: [String] = ${JSON.stringify(Object.keys(guides))}
  public static let resources: [JSONValue] = (["context"] + topics).map { topic in
    .object(["name": .string("tonk-guide-" + topic), "uri": .string("tonk://guide/" + topic),
      "mimeType": .string("text/markdown")])
  }
  public static func resource(_ uri: String) throws -> JSONValue {
    guard let item = resources.first(where: { $0["uri"].string == uri }) else {
      throw HarnessError.message("Unknown guide resource.")
    }
    let topic = String(uri.dropFirst("tonk://guide/".count))
    return .object(["contents": .array([.object([
      "uri": item["uri"], "mimeType": item["mimeType"],
      "text": .string(topic == "context" ? instructions : guides[topic]!)])])])
  }

  public static let workerScript = ${swiftString(
    bundled.outputFiles[0].text +
      `
try {
  const result = await TonkAgent.createAgentTools({subject, request: (path, options) => fetch(path, options)})
    .call(tool, JSON.parse(argumentsJSON), AbortSignal.timeout(60000));
  return {response: JSON.stringify(result)};
} catch (error) {
  return {error: error.message};
}
`,
  )}
}
`;
function swiftString(text) {
  // Raw multiline literals preserve Markdown, JSON and bundled JavaScript exactly.
  let hashes = '#';
  while (text.includes('"' + hashes) || text.includes('\\' + hashes)) hashes += '#';
  return hashes + '"""\n' + text + '\n"""' + hashes;
}
const outputs = [
  ['Sources/HarnessCore/TonkToolCatalog.generated.swift', output],
  ['Sources/HarnessCore/TonkAgentContext.generated.swift', context],
];
for (const [path, content] of outputs) {
  const target = resolve(desktop, path);
  if (check) {
    if ((await readFile(target, 'utf8').catch(() => '')) !== content) {
      console.error(path + ' is out of date. Run sync-desktop.mjs without --check.');
      process.exitCode = 1;
    }
  } else await writeFile(target, content);
}
